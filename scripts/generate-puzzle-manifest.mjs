import { readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const root = 'src/assets/puzzle-images';
const categories = { animals: 'Animals', nature: 'Nature', space: 'Space', vehicles: 'Vehicles' };
const entries = [];
for (const [folder, category] of Object.entries(categories)) {
  for (const filename of readdirSync(join(root, folder)).sort()) {
    if (!filename.endsWith('.avif')) continue;
    const match = /^([a-z0-9]+(?:-[a-z0-9]+)*)--(easy|medium|hard)\.avif$/.exec(filename);
    if (!match) throw Error('Invalid puzzle filename: ' + filename);
    const [, slug, artworkComplexity] = match;
    const title = slug.split('-').map(word => word[0].toUpperCase() + word.slice(1)).join(' ');
    entries.push({ id: folder + '-' + slug, title, category, artworkComplexity, image: '/assets/puzzle-images/' + folder + '/' + filename, description: title + ' — an illustrated ' + category.toLowerCase() + ' puzzle' });
  }
}
if (new Set(entries.map(p => p.id)).size !== entries.length) throw Error('Duplicate puzzle IDs');
mkdirSync('src/content/generated', { recursive: true });
writeFileSync('src/content/generated/puzzle-manifest.ts', '// Generated by scripts/generate-puzzle-manifest.mjs; do not edit.\nimport type { Puzzle } from "../puzzles";\nexport const generatedPuzzles: readonly Puzzle[] = ' + JSON.stringify(entries, null, 2) + ';\n');
