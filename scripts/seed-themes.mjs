async function exists(path) {
  try { await access(path); return true; } catch { return false; }
}

function render(t) {
  return `---
id: ${t.id}
title: ${t.title}
category: ${t.category}
difficulty: ${t.difficulty}
---

# Scene

${t.scene}

# Composition

${t.composition}

# Color direction

${t.color}

# Special instructions

${SPECIAL}
`;
}

const byCat = {};
for (const t of themes) {
  if (EXISTING.has(t.id)) throw new Error('Seed overlaps existing id: ' + t.id);
  byCat[t.category] ??= { easy: 0, medium: 0, hard: 0 };
  byCat[t.category][t.difficulty]++;
  const path = join(root, t.category, t.id + '.md');
  if (await exists(path)) {
    console.log('skip existing', path);
    continue;
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, render(t));
  console.log('wrote', path);
}

console.log('new theme counts by category/difficulty:', byCat);
console.log('total new themes:', themes.length);
